# 9. supondo um retângulo de 10cm de base e 5cm de altura, imprimir a seguinte saída perímetro: / área: /
# diagonal:

base = 10
alt = 5
perimetro = 2 * (base + alt)
area = base * alt   
diagonal = (base ** 2 + alt ** 2) ** 0.5
print("perimetro: ", perimetro, "/ area: ", area, "/ diagonal: ", diagonal)